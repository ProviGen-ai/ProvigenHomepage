"use client";

/**
 * Renders text as a dot-matrix display (5x7 grid per character).
 * Each letter is composed of complete, unclipped circular dots.
 */

// 5 columns x 7 rows per character, encoded as 7 hex values (each 5 bits wide)
const CHAR_MAP: Record<string, number[]> = {
  A: [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
  B: [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
  C: [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E],
  D: [0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E],
  E: [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
  F: [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
  G: [0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0E],
  H: [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
  I: [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
  J: [0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C],
  K: [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
  L: [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
  M: [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11],
  N: [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
  O: [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
  P: [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
  Q: [0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D],
  R: [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
  S: [0x0E, 0x11, 0x10, 0x0E, 0x01, 0x11, 0x0E],
  T: [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
  U: [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
  V: [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
  W: [0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11],
  X: [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
  Y: [0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04],
  Z: [0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F],
  "0": [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
  "1": [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
  "2": [0x0E, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1F],
  "3": [0x0E, 0x11, 0x01, 0x06, 0x01, 0x11, 0x0E],
  "4": [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
  "5": [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
  "6": [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
  "7": [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
  "8": [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
  "9": [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
  " ": [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
};

const DotMatrixText = ({
  text,
  color = "#0b1f30",
  dotSize = 2.5,
  gap = 1.5,
  className = "",
}: {
  text: string;
  color?: string;
  dotSize?: number;
  gap?: number;
  className?: string;
}) => {
  const cellSize = dotSize + gap;
  const charWidth = 5 * cellSize;
  const charHeight = 7 * cellSize;
  const charGap = cellSize * 1.5; // space between characters

  const chars = text.toUpperCase().split("");

  // Compute actual used width per character (rightmost active column + 1)
  const charActualCols = chars.map((char) => {
    const pattern = CHAR_MAP[char];
    if (!pattern) return 5;
    let maxCol = 0;
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if ((pattern[row] >> (4 - col)) & 1) maxCol = Math.max(maxCol, col);
      }
    }
    return maxCol + 1;
  });

  // Kerning overrides for specific letter pairs (reduce gap)
  const kernPairs: Record<string, number> = {
    "LY": -cellSize * 0.8,
    "SI": -cellSize * 0.5,
    "NI": -cellSize * 0.5,
    "DI": -cellSize * 0.5,
    "EI": -cellSize * 0.5,
    "AI": -cellSize * 0.5,
    "RI": -cellSize * 0.5,
    "IM": cellSize * 0.4,
    "IG": cellSize * 0.4,
    "IN": cellSize * 0.4,
    "IZ": cellSize * 0.4,
    "PE": -cellSize * 0.3,
  };

  // Build x offsets with tighter gaps for narrow characters
  const offsets: number[] = [];
  let x = 0;
  chars.forEach((_, ci) => {
    offsets.push(x);
    const usedWidth = charActualCols[ci] * cellSize;
    const pair = ci < chars.length - 1 ? chars[ci] + chars[ci + 1] : "";
    const kern = kernPairs[pair] || 0;
    x += usedWidth + charGap + kern;
  });
  const totalWidth = x - charGap;

  const dots: { cx: number; cy: number }[] = [];

  chars.forEach((char, ci) => {
    const pattern = CHAR_MAP[char];
    if (!pattern) return;

    const offsetX = offsets[ci];

    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        const bit = (pattern[row] >> (4 - col)) & 1;
        if (bit) {
          dots.push({
            cx: offsetX + col * cellSize + dotSize / 2,
            cy: row * cellSize + dotSize / 2,
          });
        }
      }
    }
  });

  return (
    <svg
      width={totalWidth}
      height={charHeight}
      viewBox={`0 0 ${totalWidth} ${charHeight}`}
      className={className}
      role="img"
      aria-label={text}
    >
      {dots.map((dot, i) => (
        <circle key={i} cx={dot.cx} cy={dot.cy} r={dotSize / 2} fill={color} />
      ))}
    </svg>
  );
};

export default DotMatrixText;
