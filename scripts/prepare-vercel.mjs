// Builds a Vercel deploy folder from a static export (competitor review R01, 3 Oct 2026).
//
// usage: node --experimental-strip-types scripts/prepare-vercel.mjs --target=preview|production [--no-build]
//   preview     → ../output/provigen-preview-vercel  provigen.convalexius.space, noindex
//   production  → ../output/provigen-site-vercel     provigen.ai, indexable
//
// 1. Static build with the target's SITE_URL and SITE_ENV (npm run build: feed, vinext).
// 2. dist/client → <out>/public (without vinext's _headers and client manifest).
// 3. The contact form's Vercel Function: <out>/api/contact.js around lib/contact/handler.ts,
//    transpiled to plain JS (static export skips app/api routes; this is the same handler).
// 4. <out>/vercel.json: the redirects from next.config.ts (one list), security headers,
//    immutable caching for hashed assets, and noindex on the preview.
// Then deploy from <out>: `npx vercel deploy --prod`. The preview folder keeps its own
// middleware.js (host redirect, optional password) and .vercel link; this script leaves both.
import { execSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { retired } from '../next.config.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const flag = (name) => process.argv.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
const target = (flag('target') ?? '--target=preview').split('=')[1];

const TARGETS = {
  preview: {
    url: 'https://provigen.convalexius.space',
    env: 'preview',
    out: join(ROOT, '..', 'output', 'provigen-preview-vercel'),
    noindex: true,
  },
  production: {
    url: 'https://provigen.ai',
    env: 'production',
    out: join(ROOT, '..', 'output', 'provigen-site-vercel'),
    noindex: false,
  },
};
const t = TARGETS[target];
if (!t) {
  console.error(`prepare-vercel: unknown --target=${target} (preview or production)`);
  process.exit(2);
}

if (!flag('no-build')) {
  execSync('npm run build', {
    cwd: ROOT,
    stdio: 'inherit',
    env: { ...process.env, STATIC_EXPORT: '1', SITE_URL: t.url, SITE_ENV: t.env },
  });
}

const dist = join(ROOT, 'dist', 'client');
if (!existsSync(join(dist, 'index.html'))) {
  console.error('prepare-vercel: dist/client/index.html is missing; run the static build first.');
  process.exit(1);
}
mkdirSync(t.out, { recursive: true });
rmSync(join(t.out, 'public'), { recursive: true, force: true });
cpSync(dist, join(t.out, 'public'), {
  recursive: true,
  filter: (src) => !/(?:^|[\\/])(?:_headers|vinext-client-entry-manifest\.json)$/.test(src),
});

const handler = join(ROOT, 'lib', 'contact', 'handler.ts');
if (existsSync(handler)) {
  const api = join(t.out, 'api');
  rmSync(api, { recursive: true, force: true });
  mkdirSync(api, { recursive: true });
  // Plain ES modules, transpiled here with the repo's TypeScript, so Vercel
  // compiles nothing with settings of its own. Underscore files in api/ are
  // not deployed as Functions of their own.
  const js = ts.transpileModule(readFileSync(handler, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  writeFileSync(join(api, '_contact-handler.js'), js);
  writeFileSync(
    join(api, 'contact.js'),
    `// Generated by provigen-website/scripts/prepare-vercel.mjs; edit lib/contact/handler.ts instead.
// Env: RESEND_API_KEY (required to send), CONTACT_TO, CONTACT_FROM, CONTACT_ORIGINS (optional).
import { handleContact } from './_contact-handler.js';

export function POST(request) {
  return handleContact(request, process.env);
}

export function GET() {
  return new Response('Method Not Allowed', { status: 405, headers: { Allow: 'POST' } });
}
`,
  );
  // ES modules for the Function files; no dependencies, nothing to install.
  writeFileSync(join(t.out, 'package.json'), `${JSON.stringify({ private: true, type: 'module' }, null, 2)}\n`);
} else {
  console.warn('prepare-vercel: lib/contact/handler.ts not found; no contact Function written.');
}

const security = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
  { key: 'Content-Security-Policy', value: "frame-ancestors 'self'" },
];
const vercel = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  framework: null,
  buildCommand: '',
  outputDirectory: 'public',
  cleanUrls: true,
  redirects: retired.map(([source, destination]) => ({ source, destination, permanent: true })),
  headers: [
    {
      source: '/(.*)',
      headers: [...security, ...(t.noindex ? [{ key: 'X-Robots-Tag', value: 'noindex, nofollow' }] : [])],
    },
    // Hashed build assets never change under their name.
    { source: '/_next/static/(.*)', headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }] },
  ],
};
writeFileSync(join(t.out, 'vercel.json'), `${JSON.stringify(vercel, null, 2)}\n`);
console.log(`prepare-vercel: ${target} ready in ${t.out} (${t.url}). Deploy there with: npx vercel deploy --prod`);
