// The SDM-1 route as Vercel Functions (13 Nov 2026), for both deploy paths:
// scripts/vercel-build.mjs (git deploys, Build Output API) and
// scripts/prepare-vercel.mjs (CLI deploys). The static export skips app/api,
// so, as for the contact form, the same handler (lib/sdm/proxy.ts, no
// imports) is transpiled here and wrapped.
//
// Node runtime, not Edge: AWS may take up to 54 s to answer and the route
// waits 57 s, which an Edge Function (first byte within 25 s) cannot.
// maxDuration 60 s (was 25 s / 26 s / 40 s until 16 Nov 2026). CommonJS with the classic (req, res) signature, adapted to
// the handler's Web Request and Response.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/** The routes: URL path under /api/sdm1 and the handler's path argument. */
export const SDM_ROUTES = [
  ['v1/status', 'status'],
  ['v1/propose', 'propose'],
  ['preview', 'preview'],
  /* The "Get access" form's token request (16 Nov 2026). */
  ['v1/tokens', 'tokens'],
  /* The magic link's activation (the user, 17 Nov 2026). */
  ['v1/activate', 'activate'],
];

// export const SDM_MAX_DURATION = 40;
/* 60 s: the Vercel free (Hobby) plan's limit without Fluid compute, so it holds either way (16 Nov 2026). */
export const SDM_MAX_DURATION = 60;

/** lib/sdm/proxy.ts as CommonJS. */
export function sdmHandlerJs() {
  return ts.transpileModule(readFileSync(join(ROOT, 'lib', 'sdm', 'proxy.ts'), 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
}

/** The (req, res) wrapper around handleSdm for one route; `handler` is the require path of the transpiled proxy. */
export function sdmWrapperJs(path, handler) {
  return `// Generated by scripts/sdm-function.mjs; edit lib/sdm/proxy.ts instead.
// Env (server only): SDM_API_BASE, SDM_API_SECRET, SDM_PREVIEW_TOKEN, SDM_PUBLIC, SDM_KILL_SWITCH.
// A new registration is mailed to SDM_NOTIFY_TO (default dev@provigen.ai) with the contact form's RESEND_API_KEY.
'use strict';
const { handleSdm } = require(${JSON.stringify(handler)});

module.exports = async function sdm(req, res) {
  try {
    const proto = String(req.headers['x-forwarded-proto'] || 'https').split(',')[0].trim();
    const url = new URL(req.url, proto + '://' + (req.headers.host || 'localhost'));
    const headers = new Headers();
    for (const [key, value] of Object.entries(req.headers)) {
      if (value !== undefined) headers.set(key, Array.isArray(value) ? value.join(', ') : String(value));
    }
    let body;
    if (req.method !== 'GET' && req.method !== 'HEAD') {
      const chunks = [];
      for await (const chunk of req) chunks.push(chunk);
      body = Buffer.concat(chunks);
    }
    const request = new Request(url, { method: req.method, headers, body });
    const response = await handleSdm(request, { ...process.env, VERCEL: process.env.VERCEL || '1', NODE_ENV: 'production' }, ${JSON.stringify(path)});
    res.statusCode = response.status;
    response.headers.forEach((value, key) => res.setHeader(key, value));
    res.end(Buffer.from(await response.arrayBuffer()));
  } catch (error) {
    console.error('sdm1: the route failed:', error && error.message);
    res.statusCode = 503;
    res.setHeader('Content-Type', 'application/json; charset=utf-8');
    res.setHeader('Retry-After', '30');
    res.setHeader('Cache-Control', 'no-store');
    res.end(JSON.stringify({ error: 'high_demand', message: 'High demand right now. Please try again in a few minutes.', retry_after_s: 30 }));
  }
};
`;
}

/** Build Output API: <functions>/api/sdm1/<route>.func, each with the proxy beside its wrapper. */
export function writeSdmBuildOutput(functionsDir) {
  const js = sdmHandlerJs();
  for (const [route, path] of SDM_ROUTES) {
    const dir = join(functionsDir, 'api', 'sdm1', `${route}.func`);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'proxy.js'), js);
    writeFileSync(join(dir, 'index.js'), sdmWrapperJs(path, './proxy.js'));
    writeFileSync(join(dir, 'package.json'), `${JSON.stringify({ private: true, type: 'commonjs' }, null, 2)}\n`);
    writeFileSync(
      join(dir, '.vc-config.json'),
      `${JSON.stringify({ runtime: 'nodejs22.x', handler: 'index.js', launcherType: 'Nodejs', shouldAddHelpers: false, maxDuration: SDM_MAX_DURATION }, null, 2)}\n`,
    );
  }
}

/**
 * CLI deploys (prepare-vercel.mjs): zero-config Functions in <out>/api, ES modules with Web
 * handlers like api/contact.js. maxDuration comes from vercel.json `functions` (SDM_FUNCTIONS).
 */
export function writeSdmApiDir(apiDir) {
  const js = ts.transpileModule(readFileSync(join(ROOT, 'lib', 'sdm', 'proxy.ts'), 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  mkdirSync(apiDir, { recursive: true });
  writeFileSync(join(apiDir, '_sdm-proxy.js'), js);
  for (const [route, path] of SDM_ROUTES) {
    const file = join(apiDir, 'sdm1', `${route}.js`);
    mkdirSync(join(file, '..'), { recursive: true });
    const depth = route.split('/').length;
    const proxy = `${'../'.repeat(depth)}_sdm-proxy.js`;
    // const verb = path === 'propose' ? 'POST' : 'GET';
    const verb = path === 'propose' || path === 'tokens' ? 'POST' : 'GET';
    writeFileSync(
      file,
      `// Generated by scripts/sdm-function.mjs; edit lib/sdm/proxy.ts instead.
// Env (server only): SDM_API_BASE, SDM_API_SECRET, SDM_PREVIEW_TOKEN, SDM_PUBLIC, SDM_KILL_SWITCH.
import { handleSdm } from '${proxy}';

export function ${verb}(request) {
  return handleSdm(request, { ...process.env, VERCEL: process.env.VERCEL || '1', NODE_ENV: 'production' }, '${path}');
}
`,
    );
  }
}

/** vercel.json `functions` entry for the CLI deploy. */
export const SDM_FUNCTIONS = { 'api/sdm1/**/*.js': { maxDuration: SDM_MAX_DURATION } };
