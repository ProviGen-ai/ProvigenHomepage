// Vercel's build for git deploys (14 Oct 2026): a push to main publishes
// provigen.ai, any other branch a preview. Same pieces as prepare-vercel.mjs
// (static export, the contact Function, redirects and headers), written in
// Vercel's Build Output API (.vercel/output) so the project needs no
// framework preset: vercel.json only points the build here.
//
// usage (Vercel runs it): node --experimental-strip-types --no-warnings scripts/vercel-build.mjs
//   VERCEL_ENV=production → SITE_URL https://provigen.ai, SITE_ENV production
//   anything else         → the deploy's own URL, SITE_ENV preview, noindex
import { execSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { retired } from '../next.config.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const production = process.env.VERCEL_ENV === 'production';
const host = process.env.VERCEL_BRANCH_URL || process.env.VERCEL_URL;
const siteUrl = production ? 'https://provigen.ai' : host ? `https://${host}` : 'http://localhost:3000';

execSync('npm run build', {
  cwd: ROOT,
  stdio: 'inherit',
  env: { ...process.env, STATIC_EXPORT: '1', SITE_URL: siteUrl, SITE_ENV: production ? 'production' : 'preview' },
});

const dist = join(ROOT, 'dist', 'client');
if (!existsSync(join(dist, 'index.html'))) {
  console.error('vercel-build: dist/client/index.html is missing; the static build did not run.');
  process.exit(1);
}

const out = join(ROOT, '.vercel', 'output');
rmSync(out, { recursive: true, force: true });
const statics = join(out, 'static');
cpSync(dist, statics, {
  recursive: true,
  filter: (src) => !/(?:^|[\\/])(?:_headers|vinext-client-entry-manifest\.json)$/.test(src),
});

// Clean URLs: every page.html is served at /page (index.html at its folder).
const overrides = {};
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (name.endsWith('.html')) {
      const rel = relative(statics, path).split(sep).join('/');
      if (rel === 'index.html') continue;
      overrides[rel] = { path: rel.replace(/(?:^|\/)index\.html$/, '').replace(/\.html$/, ''), contentType: 'text/html; charset=utf-8' };
    }
  }
};
walk(statics);

// The contact form's Function: lib/contact/handler.ts (no imports) as one Edge module.
const handler = readFileSync(join(ROOT, 'lib', 'contact', 'handler.ts'), 'utf8');
const js = ts.transpileModule(handler, {
  compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
}).outputText;
const fn = join(out, 'functions', 'api', 'contact.func');
mkdirSync(fn, { recursive: true });
writeFileSync(
  join(fn, 'index.js'),
  `// Generated by scripts/vercel-build.mjs; edit lib/contact/handler.ts instead.
${js}
export default function contact(request) {
  return handleContact(request, { ...process.env, VERCEL: '1' });
}
`,
);
writeFileSync(join(fn, '.vc-config.json'), `${JSON.stringify({ runtime: 'edge', entrypoint: 'index.js' }, null, 2)}\n`);

const security = {
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
  'Content-Security-Policy': "frame-ancestors 'self'",
  ...(production ? {} : { 'X-Robots-Tag': 'noindex, nofollow' }),
};
const escape = (path) => path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const config = {
  version: 3,
  routes: [
    // Retired URLs from next.config.ts, permanent.
    ...retired.map(([source, destination]) => ({
      src: `^${escape(source)}/?$`,
      headers: { Location: destination },
      status: 308,
    })),
    // page.html and trailing slashes land on the clean URL.
    { src: '^/(.+)\\.html$', headers: { Location: '/$1' }, status: 308 },
    { src: '^/(.+)/$', headers: { Location: '/$1' }, status: 308 },
    { src: '^/(.*)$', headers: security, continue: true },
    { src: '^/_next/static/(.*)$', headers: { 'Cache-Control': 'public, max-age=31536000, immutable' }, continue: true },
    { handle: 'filesystem' },
    { src: '^/api/contact$', dest: '/api/contact' },
    { handle: 'miss' },
    { src: '^/(.*)$', dest: '/404', status: 404 },
  ],
  overrides,
};
writeFileSync(join(out, 'config.json'), `${JSON.stringify(config, null, 2)}\n`);
console.log(`vercel-build: ${production ? 'production' : 'preview'} build for ${siteUrl} in .vercel/output`);
